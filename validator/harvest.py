"""Ask the game which control-behaviour settings Draftsman can't express.

    python -m validator.harvest [--factorio PATH]

Places every placeable entity in a headless server, flips every writable
boolean and network selection its control behaviour has (from that version's
Lua API docs), exports each one, and loads the exports with Draftsman. Keys
Draftsman parks in `extra_keys` are game settings it doesn't model; they go
to tools/game_settings.json, by prototype type, with the value the game wrote
and the entities it was written for.
tools/settings.py lets generators set exactly those keys.

Only settings reachable by flipping booleans and network selections are
found. A setting that needs another value type to show up in an export
(a chosen signal, a number) is not in the registry until harvested another way.
"""

import argparse
import json
import sys
import urllib.request
import warnings
from pathlib import Path

import draftsman
from draftsman.blueprintable import get_blueprintable_from_JSON

from tools.codec import decode, dump_json
from tools.settings import flatten, kind
from validator.server import Server

API = "https://lua-api.factorio.com/{version}/runtime-api.json"
OUT = Path(__file__).resolve().parent.parent / "tools" / "game_settings.json"


def flip_spec(version: str) -> dict:
    """{LuaXControlBehavior: {"b": [bool attrs], "n": [network attrs]}} from the API docs."""
    request = urllib.request.Request(API.format(version=version), headers={"User-Agent": "ghostwriter-validator"})
    with urllib.request.urlopen(request) as resp:
        api = json.load(resp)
    classes = {c["name"]: c for c in api["classes"]}

    def attributes(name):
        c = classes[name]
        return c["attributes"] + (attributes(c["parent"]) if c.get("parent") else [])

    spec = {}
    for name in classes:
        if name.endswith("ControlBehavior"):
            attrs = attributes(name)
            spec[name] = {
                "b": [a["name"] for a in attrs if a.get("write_type") == "boolean"],
                "n": [a["name"] for a in attrs if a.get("write_type") == "CircuitNetworkSelection"],
            }
    return spec


def build_registry(exports: list[dict]) -> tuple[dict, dict]:
    types, unsupported = {}, {}
    for export in exports:
        data = decode(export["string"])
        try:
            with warnings.catch_warnings():
                warnings.simplefilter("ignore")
                model = get_blueprintable_from_JSON(data)
        except Exception as e:  # Draftsman bugs on some 2.1 entities (NOTES.md)
            unsupported[export["name"]] = f"Draftsman can't load it: {type(e).__name__}"
            continue
        for entity in model.entities:
            if type(entity).__name__ == "Entity":
                unsupported[entity.name] = "Draftsman has no class for this type"
                continue
            cb = (entity.extra_keys or {}).get("control_behavior")
            if not cb:
                continue
            entry = types.setdefault(export["type"], {"examples": [], "settings": {}})
            if entity.name not in entry["examples"]:
                entry["examples"].append(entity.name)
            for path, value in flatten(cb):
                setting = entry["settings"].setdefault(path, {"kind": kind(value), "observed": value, "entities": []})
                # Per entity: the same prototype type can differ (an electric
                # assembler has no fuel to read; a provider chest sets no requests).
                if entity.name not in setting["entities"]:
                    setting["entities"].append(entity.name)
    return types, unsupported


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--factorio")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args(argv)
    with Server(args.factorio) as server:
        spec = flip_spec(server.version)
        result = server.call("harvest", json.dumps(spec))
    types, unsupported = build_registry(result["exports"])
    registry = {
        "game_version": server.version,
        "draftsman_version": draftsman.__version__,
        "note": "Generated by `python -m validator.harvest`; do not edit by hand.",
        "types": dict(sorted(types.items())),
        "unsupported": dict(sorted(unsupported.items())),
    }
    Path(args.out).write_text(dump_json(registry))
    n = sum(len(t["settings"]) for t in types.values())
    print(f"{n} settings on {len(types)} prototype types -> {args.out}", file=sys.stderr)
    print(f"not placeable on the test surface: {', '.join(result['unplaceable']) or 'none'}", file=sys.stderr)


if __name__ == "__main__":
    main()
